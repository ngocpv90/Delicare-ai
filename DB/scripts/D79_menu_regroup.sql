DECLARE @C TABLE (Id UNIQUEIDENTIFIER PRIMARY KEY, Link NVARCHAR(400), OldParentId UNIQUEIDENTIFIER NULL, NewParentId UNIQUEIDENTIFIER NULL, OldOrder INT NULL, NewOrder INT NULL,
