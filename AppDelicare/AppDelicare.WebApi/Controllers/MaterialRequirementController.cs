        [HttpGet("GetByDate")]
        public async Task<IActionResult> GetByDate([FromQuery] MaterialRequirementByDateRequest request)
        {
            try
            {
                if (!ModelState.IsValid || null == request)
                {
                    return BadRequest(ConstantHelper.Message.ModelStateMessage);
