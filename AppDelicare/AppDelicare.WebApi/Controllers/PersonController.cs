        [HttpPut("UpdateProfile")]
        public async Task<IActionResult> UpdateProfile([FromForm] PersonCustomRequest request)
        {
            try
            {
                if (!ModelState.IsValid || null == request)
                {
                    return BadRequest(ConstantHelper.Message.ModelStateMessage);
                }
