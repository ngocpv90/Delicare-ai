/// Nguồn DUY NHẤT: Menu5Groups (nhóm, thứ tự), HiddenNow (ẩn), MenuRenames / Menu5Renames / Menu5NewItems (tên), ScreenMatrix (quyền 19 nhóm chuẩn theo Code).
/// Sinh: DB/seed/Z_Menu_sync.sql (đặt đúng trạng thái đích mục nguồn – không phụ thuộc thứ tự cũ; mục / nhóm admin tự tạo ngoài nguồn giữ nguyên) và
