    public sealed record MenuTarget(string Link, int Level, string? Parent, int Order, string? Name, string ShortName, bool Active);

    /// <summary>Trạng thái đích của mọi mục menu do nguồn quản (nhóm cấp 1 + mục cấp 2 trong Menu5Groups).</summary>
    public static List<MenuTarget> MenuTargets(List<Screen> screens)
    {
        var list = new List<MenuTarget>();
        foreach (var g in Menu5Groups)
        {
            list.Add(new MenuTarget(g.Link, 1, null, g.Order, g.Name, g.ShortName, !HiddenNow.Contains(g.Link))); // tên nhóm MENU-5 mới hơn MenuRenames cũ
            int i = 0;
            foreach (string item in g.Items)
            {
                i++;
                string link = "#/" + item;
                int order = g.Link == ApprovalGroupLink ? 9900 + i : g.Order + i;
                string? baseName = Menu5NewItems.TryGetValue(item, out var nw) ? nw.Name
                    : Menu5Renames.TryGetValue(item, out var rn) ? rn.New
                    : screens.FirstOrDefault(s => s.Id == item)?.Name;
                string? name = MenuRenames.Any(r => r.Link == link) ? MenuName(link, baseName ?? string.Empty) : baseName;
                string shortName = Menu5NewItems.TryGetValue(item, out var nw2) ? nw2.Phase : string.Empty;
                list.Add(new MenuTarget(link, 2, g.Link, order, string.IsNullOrEmpty(name) ? null : name, shortName, !HiddenNow.Contains(link)));
            }
        }
        return list;
    }

    private static void AppendTargets(StringBuilder sb, List<Screen> screens)
    {
        sb.AppendLine("DECLARE @T TABLE (Link NVARCHAR(400) PRIMARY KEY, Lvl INT, Parent NVARCHAR(400) NULL, Ord INT, Name NVARCHAR(500) NULL, ShortName NVARCHAR(100), Active BIT);");
        string N(string? v) => v == null ? "NULL" : Sql(v);
        AppendValues(sb, "@T", [.. MenuTargets(screens).Select(t => $"({Sql(t.Link)}, {t.Level}, {N(t.Parent)}, {t.Order}, {N(t.Name)}, {Sql(t.ShortName)}, {(t.Active ? 1 : 0)})")]);
    }

    /// <summary>DB/seed/Z_Menu_sync.sql – chạy trong scripts.order (sau mọi seed menu cũ). Không cần tham số; chạy lại = 0 thay đổi.</summary>
    public static string MenuSyncScript(List<Screen> screens)
    {
        var sb = new StringBuilder();
        sb.AppendLine("""
            -- <auto-generated> tools/AppDelicare.CodeGen (DEPLOY-SYNC-1, D-134) – nguồn Seeds.Menu5.cs / Seeds.cs. Không sửa tay.
            -- Đặt MỌI mục menu do nguồn quản về trạng thái đích: có mặt, nhóm cha, thứ tự, tên, bật / tắt (mục cấp 2 + nhóm cấp 1 của Menu5Groups).
            -- Hội tụ: không phụ thuộc thứ tự / tên cũ; DB nào (mới, cũ, đã chạy tay) chạy xong đều giống nhau. Mục / nhóm admin tự tạo NGOÀI nguồn: giữ nguyên.
            -- Không DELETE. Mỗi mục đổi ghi 1 dòng AuditChange (Action MenuSync). Chạy lại = 0 thay đổi. Kiểm: DB/scripts/CHECK_menu_permission.sql.
            SET NOCOUNT ON;
            SET XACT_ABORT ON;
            DECLARE @By UNIQUEIDENTIFIER = ISNULL((SELECT TOP 1 Id FROM dbo.[User] WHERE UserName = N'system' AND ISNULL(IsDeleted, 0) = 0),
                                                  (SELECT TOP 1 Id FROM dbo.[User] WHERE UserName = N'admin' AND ISNULL(IsDeleted, 0) = 0));
            IF @By IS NULL THROW 50001, N'Không có tài khoản system / admin để ghi người thao tác.', 1;
            DECLARE @Now DATETIME = DATEADD(HOUR, 7, SYSUTCDATETIME());
            BEGIN TRANSACTION;
            """);
        AppendTargets(sb, screens);
        sb.AppendLine("""
            DECLARE @Changed TABLE (Id UNIQUEIDENTIFIER, Link NVARCHAR(400), What NVARCHAR(400));
            -- 1. Thêm nhóm / mục còn thiếu (mục cấp 2 cần nhóm cha có sẵn – nhóm thêm trước).
            INSERT INTO dbo.ObjectMenu (Id, Name, ShortName, MetaLink, ParentId, LevelShow, OrderShow, IsActive, IsDefault, CreatedDate, CreatedBy, IsDeleted)
            OUTPUT inserted.Id, inserted.MetaLink, N'Thêm' INTO @Changed
            SELECT NEWID(), ISNULL(t.Name, t.Link), t.ShortName, t.Link, NULL, 1, t.Ord, t.Active, 0, @Now, @By, 0
            FROM @T t WHERE t.Lvl = 1 AND NOT EXISTS (SELECT 1 FROM dbo.ObjectMenu m WHERE m.MetaLink = t.Link AND ISNULL(m.IsDeleted, 0) = 0);
            INSERT INTO dbo.ObjectMenu (Id, Name, ShortName, MetaLink, ParentId, LevelShow, OrderShow, IsActive, IsDefault, CreatedDate, CreatedBy, IsDeleted)
            OUTPUT inserted.Id, inserted.MetaLink, N'Thêm' INTO @Changed
            SELECT NEWID(), ISNULL(t.Name, t.Link), t.ShortName, t.Link, p.Id, 2, t.Ord, t.Active, 0, @Now, @By, 0
            FROM @T t CROSS APPLY (SELECT TOP 1 Id FROM dbo.ObjectMenu WHERE MetaLink = t.Parent AND ISNULL(IsDeleted, 0) = 0 ORDER BY CreatedDate) p
            WHERE t.Lvl = 2 AND NOT EXISTS (SELECT 1 FROM dbo.ObjectMenu m WHERE m.MetaLink = t.Link AND ISNULL(m.IsDeleted, 0) = 0);
            -- 2. Đặt đúng nhóm cha / thứ tự / tên / bật-tắt / cấp cho mục đã có.
            UPDATE m SET m.ParentId = CASE WHEN t.Lvl = 1 THEN NULL ELSE p.Id END, m.OrderShow = t.Ord, m.Name = ISNULL(t.Name, m.Name), m.IsActive = t.Active, m.LevelShow = t.Lvl,
                         m.ModifiedDate = @Now, m.ModifiedBy = @By
            OUTPUT inserted.Id, inserted.MetaLink, CONCAT(N'Sửa: ', deleted.Name, N' → ', inserted.Name, N'; thứ tự ', deleted.OrderShow, N' → ', inserted.OrderShow,
                   N'; bật ', CAST(deleted.IsActive AS INT), N' → ', CAST(inserted.IsActive AS INT)) INTO @Changed
            FROM dbo.ObjectMenu m
            JOIN @T t ON t.Link = m.MetaLink
            OUTER APPLY (SELECT TOP 1 Id FROM dbo.ObjectMenu WHERE MetaLink = t.Parent AND ISNULL(IsDeleted, 0) = 0 ORDER BY CreatedDate) p
            WHERE ISNULL(m.IsDeleted, 0) = 0
              AND (ISNULL(m.OrderShow, -1) <> t.Ord OR ISNULL(m.IsActive, 0) <> t.Active OR ISNULL(m.LevelShow, -1) <> t.Lvl
                   OR (t.Name IS NOT NULL AND ISNULL(m.Name, N'') <> t.Name)
                   OR (t.Lvl = 1 AND m.ParentId IS NOT NULL) OR (t.Lvl = 2 AND p.Id IS NOT NULL AND ISNULL(m.ParentId, '00000000-0000-0000-0000-000000000000') <> p.Id));
            INSERT INTO dbo.AuditChange (Id, IdChange, Action, EntityName, Changes, CreatedDate, CreatedBy, IsDeleted)
            SELECT NEWID(), c.Id, N'MenuSync', N'ObjectMenu', LEFT(CONCAT(N'- DEPLOY-SYNC-1 (D-134): ', c.Link, N' – ', c.What), 4000), @Now, @By, 0 FROM @Changed c;
            SELECT COUNT(*) AS [Mục menu thêm / sửa (D-134)] FROM @Changed;
            COMMIT TRANSACTION;
            """);
        return sb.ToString();
    }

    /// <summary>DB/scripts/CHECK_menu_permission.sql – in lệch menu / quyền / script chuyển đổi chưa chạy; 0 dòng = đúng; có lệch → lỗi (sqlcmd -b dừng quy trình).</summary>
    public static string CheckScript(List<Screen> screens, IEnumerable<string> onceScripts)
    {
        var sb = new StringBuilder();
        sb.AppendLine("""
            -- <auto-generated> tools/AppDelicare.CodeGen (DEPLOY-SYNC-1.5, D-134) – CÙNG NGUỒN với Z_Menu_sync.sql + D79_permission_matrix.sql. Không sửa tay.
            -- Tự kiểm sau cập nhật: (1) menu do nguồn quản – thiếu / sai nhóm / sai thứ tự / sai tên / sai bật-tắt; (2) ô quyền 19 nhóm chuẩn (theo UserGroup.Code)
            -- trên mục cấp 2 đang bật lệch ma trận; (3) script chuyển đổi 1 lần chưa ghi nhận. 0 dòng lệch = đúng; có lệch → RAISERROR (Deploy-Database / db-init dừng).
            --   sqlcmd -S <server> -d <db> -E -b -I -f 65001 -i DB/scripts/CHECK_menu_permission.sql -W -s "|"
            SET NOCOUNT ON;
            DECLARE @Out TABLE (Loai NVARCHAR(40), Muc NVARCHAR(400), ChiTiet NVARCHAR(1000));
            """);
        AppendTargets(sb, screens);
        sb.AppendLine("""
            INSERT INTO @Out
            SELECT N'Menu – thiếu', t.Link, ISNULL(t.Name, N'') FROM @T t
            WHERE NOT EXISTS (SELECT 1 FROM dbo.ObjectMenu m WHERE m.MetaLink = t.Link AND ISNULL(m.IsDeleted, 0) = 0);
            INSERT INTO @Out
            SELECT N'Menu – lệch', t.Link,
                   CONCAT(CASE WHEN t.Lvl = 2 AND ISNULL(pm.MetaLink, N'') <> t.Parent THEN CONCAT(N'nhóm ', ISNULL(pm.MetaLink, N'(không)'), N' ≠ ', t.Parent, N'; ') ELSE N'' END,
                          CASE WHEN ISNULL(m.OrderShow, -1) <> t.Ord THEN CONCAT(N'thứ tự ', m.OrderShow, N' ≠ ', t.Ord, N'; ') ELSE N'' END,
                          CASE WHEN t.Name IS NOT NULL AND ISNULL(m.Name, N'') <> t.Name THEN CONCAT(N'tên «', m.Name, N'» ≠ «', t.Name, N'»; ') ELSE N'' END,
                          CASE WHEN ISNULL(m.IsActive, 0) <> t.Active THEN CONCAT(N'bật ', CAST(m.IsActive AS INT), N' ≠ ', CAST(t.Active AS INT), N'; ') ELSE N'' END,
                          CASE WHEN ISNULL(m.LevelShow, -1) <> t.Lvl THEN CONCAT(N'cấp ', m.LevelShow, N' ≠ ', t.Lvl) ELSE N'' END)
            FROM @T t JOIN dbo.ObjectMenu m ON m.MetaLink = t.Link AND ISNULL(m.IsDeleted, 0) = 0
            LEFT JOIN dbo.ObjectMenu pm ON pm.Id = m.ParentId
            WHERE (t.Lvl = 2 AND ISNULL(pm.MetaLink, N'') <> t.Parent) OR ISNULL(m.OrderShow, -1) <> t.Ord OR (t.Name IS NOT NULL AND ISNULL(m.Name, N'') <> t.Name)
               OR ISNULL(m.IsActive, 0) <> t.Active OR ISNULL(m.LevelShow, -1) <> t.Lvl;
            """);
        sb.AppendLine("DECLARE @Roles TABLE (Name NVARCHAR(100) PRIMARY KEY);");
        AppendValues(sb, "@Roles", [.. StandardRoles.Select(r => $"({Sql(r)})")]);
        sb.AppendLine("DECLARE @Allow TABLE (GroupName NVARCHAR(100), MetaLink NVARCHAR(300), A BIT, Ad BIT, E BIT, D BIT, P BIT, X BIT, I BIT, PRIMARY KEY (GroupName, MetaLink));");
        AppendValues(sb, "@Allow", MatrixRows(nonZeroOnly: true));
        sb.AppendLine("""
            INSERT INTO @Out
            SELECT N'Quyền – lệch', CONCAT(r.Name, N' × ', m.MetaLink),
                   CONCAT(N'có ', CONCAT(ISNULL(CAST(ur.AllowAccess AS INT), 0), ISNULL(CAST(ur.AllowAdd AS INT), 0), ISNULL(CAST(ur.AllowEdit AS INT), 0), ISNULL(CAST(ur.AllowDelete AS INT), 0),
                                     ISNULL(CAST(ur.AllowPrint AS INT), 0), ISNULL(CAST(ur.AllowExport AS INT), 0), ISNULL(CAST(ur.AllowImport AS INT), 0)),
                          N' – cần ', CONCAT(ISNULL(CAST(a.A AS INT), 0), ISNULL(CAST(a.Ad AS INT), 0), ISNULL(CAST(a.E AS INT), 0), ISNULL(CAST(a.D AS INT), 0),
                                     ISNULL(CAST(a.P AS INT), 0), ISNULL(CAST(a.X AS INT), 0), ISNULL(CAST(a.I AS INT), 0)), N' (XemThemSuaXoaInXuatNhap)')
            FROM dbo.UserGroup g
            JOIN @Roles r ON r.Name = ISNULL(NULLIF(g.Code, N''), g.Name)
            CROSS JOIN dbo.ObjectMenu m
            LEFT JOIN @Allow a ON a.GroupName = r.Name AND a.MetaLink = m.MetaLink
            OUTER APPLY (SELECT TOP 1 x.* FROM dbo.UserRole x WHERE x.UserGroupId = g.Id AND x.ObjectMenuId = m.Id AND ISNULL(x.IsDeleted, 0) = 0 ORDER BY x.CreatedDate) ur
            WHERE ISNULL(g.IsDeleted, 0) = 0 AND ISNULL(m.IsDeleted, 0) = 0 AND m.IsActive = 1 AND m.LevelShow = 2 AND m.MetaLink LIKE N'#/%'
              AND m.MetaLink NOT IN (N'#/bot-van-hanh', N'#/bot-dieu-hanh')
              AND (ISNULL(ur.AllowAccess, 0) <> ISNULL(a.A, 0) OR ISNULL(ur.AllowAdd, 0) <> ISNULL(a.Ad, 0) OR ISNULL(ur.AllowEdit, 0) <> ISNULL(a.E, 0)
                OR ISNULL(ur.AllowDelete, 0) <> ISNULL(a.D, 0) OR ISNULL(ur.AllowPrint, 0) <> ISNULL(a.P, 0) OR ISNULL(ur.AllowExport, 0) <> ISNULL(a.X, 0)
                OR ISNULL(ur.AllowImport, 0) <> ISNULL(a.I, 0));
            INSERT INTO @Out
            SELECT N'Quyền – nhóm trùng', r.Name, CONCAT(COUNT(g.Id), N' nhóm cùng mã – giữ 1 (dọn: DB/scripts/SYNC1_dedupe_usergroups.sql)') FROM @Roles r
            JOIN dbo.UserGroup g ON ISNULL(NULLIF(g.Code, N''), g.Name) = r.Name AND ISNULL(g.IsDeleted, 0) = 0 GROUP BY r.Name HAVING COUNT(g.Id) > 1;
            INSERT INTO @Out
            SELECT N'Quyền – thiếu nhóm', r.Name, N'chưa có nhóm quyền chuẩn' FROM @Roles r
            WHERE NOT EXISTS (SELECT 1 FROM dbo.UserGroup g WHERE ISNULL(NULLIF(g.Code, N''), g.Name) = r.Name AND ISNULL(g.IsDeleted, 0) = 0);
            """);
        sb.AppendLine("DECLARE @Once TABLE (FileName NVARCHAR(300) PRIMARY KEY);");
        var once = onceScripts.ToList();
        if (once.Count > 0)
        {
            AppendValues(sb, "@Once", [.. once.Select(f => $"({Sql(f)})")]);
        }
        sb.AppendLine("""
            INSERT INTO @Out
            SELECT N'Chuyển đổi – chưa chạy', o.FileName, N'chưa ghi nhận DelicareOnce (chạy Deploy-Database / db-init)' FROM @Once o
            WHERE NOT EXISTS (SELECT 1 FROM sys.extended_properties p WHERE p.class = 0 AND p.name = N'DelicareOnce:' + o.FileName);

            SELECT Loai AS [Loại], Muc AS [Mục], ChiTiet AS [Chi tiết] FROM @Out ORDER BY Loai, Muc;
            DECLARE @N INT = (SELECT COUNT(*) FROM @Out);
            SELECT @N AS [Số dòng lệch (0 = đúng)];
            IF @N > 0 RAISERROR(N'CHECK menu / quyền: %d dòng lệch – xem danh sách phía trên (D-134).', 16, 1, @N);
            """);
        return sb.ToString();
    }
