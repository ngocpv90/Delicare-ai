    /// <param name="extraParams">Tham số mà service cũ đang truyền (phải khai báo để không lỗi "too many arguments").</param>
    public string StoredProcedure(Table t, IEnumerable<string> extraParams)
    {
        string cls = Metadata.ClassOf(t.Name);
        var view = ViewColumns(t);
        var filters = Filters(t);
        var declared = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "SearchText", "Page", "PageSize", "SortField", "SortOrder" };
        var paramLines = new List<string> { "@SearchText NVARCHAR(MAX) = NULL" };
        var where = new List<string>();

        foreach (var f in filters)
        {
            declared.Add(f.Name);
            paramLines.Add($"@{f.Name} {f.SqlParamType} = NULL");
            where.Add(f.IsString
                ? $"(ISNULL(@{f.Name}, '') = '' OR t.[{f.Name}] = @{f.Name})"
                : $"(@{f.Name} IS NULL OR t.[{f.Name}] = @{f.Name})");
        }
        foreach (string p in extraParams.Where(p => !declared.Contains(p)))
        {
            declared.Add(p);
            var col = t.Find(p);
            if (col != null)
            {
                paramLines.Add($"@{col.Name} {col.SqlParamType} = NULL");
                where.Add(col.IsString
                    ? $"(ISNULL(@{col.Name}, '') = '' OR t.[{col.Name}] LIKE CONCAT('%', @{col.Name}, '%'))"
                    : $"(@{col.Name} IS NULL OR t.[{col.Name}] = @{col.Name})");
            }
            else
            {
                paramLines.Add($"@{p} NVARCHAR(MAX) = NULL -- service cũ có truyền, bảng không có cột tương ứng: bỏ qua");
            }
        }
        paramLines.Add("@Page INT = 1");
        paramLines.Add("@PageSize INT = 10");
        paramLines.Add("@SortField NVARCHAR(100) = NULL");
        paramLines.Add("@SortOrder NVARCHAR(20) = NULL");

        var searchCols = meta.BusinessColumns(t)
            .Where(c => c.IsString && (c.Name is "Code" or "Name" or "FullName" or "DisplayName" or "Title"
                || c.Name.EndsWith("Number", StringComparison.Ordinal) || c.Name.EndsWith("No", StringComparison.Ordinal)
                || c.Name.EndsWith("Code", StringComparison.Ordinal) || c.Name.EndsWith("Name", StringComparison.Ordinal)))
            .ToList();
        string search = searchCols.Count == 0
            ? "1 = 1"
            : "(ISNULL(@SearchText, '') = '' OR " + string.Join(" OR ", searchCols.Select(c => $"t.[{c.Name}] LIKE CONCAT('%', @SearchText, '%')")) + ")";
        where.Insert(0, search);
        where.Add("t.IsDeleted = 0");

        var select = new List<string> { "t.[Id]" };
        var joins = new List<string>();
        var sortable = new List<(string Field, string Expr)>();
        int j = 0;
        foreach (var (c, label, target, labelColumn) in view)
        {
            select.Add($"t.[{c.Name}]{(PropertyName(cls, c.Name) != c.Name ? $" AS [{PropertyName(cls, c.Name)}]" : string.Empty)}");
            sortable.Add((Metadata.Camel(PropertyName(cls, c.Name)), $"r.[{PropertyName(cls, c.Name)}]"));
            if (label != null)
            {
                j++;
                joins.Add($"LEFT JOIN [dbo].[{target!.Name}] AS j{j} ON j{j}.[Id] = t.[{c.Name}]");
                select.Add($"j{j}.[{labelColumn}] AS [{label}]");
                sortable.Add((Metadata.Camel(label), $"r.[{label}]"));
            }
        }
        select.Add("t.[CreatedDate]");
        sortable.Add(("createdDate", "r.[CreatedDate]"));

        var order = new StringBuilder();
        foreach (var (field, expr) in sortable)
        {
            order.AppendLine($"\t\tCASE WHEN @SortOrder = 'ascend' AND @SortField = '{field}' THEN {expr} END ASC,");
            order.AppendLine($"\t\tCASE WHEN @SortOrder = 'descend' AND @SortField = '{field}' THEN {expr} END DESC,");
        }

        return $"""
        -- {Header[3..]}
        SET ANSI_NULLS ON
        GO
        SET QUOTED_IDENTIFIER ON
        GO
        CREATE OR ALTER PROCEDURE [dbo].[usp{cls}_GetAll] (
        	{string.Join("\n\t, ", paramLines)})
        AS
        BEGIN
        	SET NOCOUNT ON;
        	IF @Page IS NULL OR @Page < 1 SET @Page = 1;
        	IF @PageSize IS NULL OR @PageSize < 1 SET @PageSize = 10;
        	IF @PageSize > 1000 SET @PageSize = 1000;

        	;WITH TempResult AS
        	(
        		SELECT
        			{string.Join("\n\t\t\t, ", select)}
        		FROM [dbo].[{t.Name}] AS t
        		{string.Join("\n\t\t", joins)}
        		WHERE {string.Join("\n\t\t\tAND ", where)}
        	),
        	TempCount (TotalRow) AS (SELECT COUNT(*) FROM TempResult)
        	SELECT r.*, c.TotalRow
        	FROM TempResult AS r CROSS JOIN TempCount AS c
        	ORDER BY
        {order}		r.[CreatedDate] DESC
        	OFFSET (@PageSize * (@Page - 1)) ROWS FETCH NEXT @PageSize ROWS ONLY
        	OPTION (RECOMPILE);
        END
        GO

        """.Replace("\r\n", "\n");
    }

