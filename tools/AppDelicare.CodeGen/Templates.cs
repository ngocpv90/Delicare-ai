    /// <summary>DEFAULT hằng số của SQL → giá trị khởi tạo C# (bỏ qua newid / getdate…).</summary>
    public static string? EntityDefault(Column c)
    {
        if (c.Default is null)
        {
            return null;
        }
        string d = c.Default.Trim();
        while (d.StartsWith('(') && d.EndsWith(')'))
        {
            d = d[1..^1].Trim();
        }
        if (c.IsString && d.StartsWith("N'", StringComparison.Ordinal) && d.EndsWith('\''))
        {
            return "\"" + Esc(d[2..^1].Replace("''", "'")) + "\"";
        }
        if (c.IsString && d.StartsWith('\'') && d.EndsWith('\''))
        {
            return "\"" + Esc(d[1..^1].Replace("''", "'")) + "\"";
        }
        if (c.ClrType == "bool" && (d == "0" || d == "1"))
        {
            return d == "1" ? "true" : null;
        }
        if (c.ClrType is "int" or "long" or "short" or "byte" && long.TryParse(d, out var n))
        {
            return n == 0 ? null : n.ToString(System.Globalization.CultureInfo.InvariantCulture);
        }
        if (c.ClrType == "decimal" && decimal.TryParse(d, System.Globalization.NumberStyles.Number, System.Globalization.CultureInfo.InvariantCulture, out var m))
        {
            return m == 0 ? null : m.ToString(System.Globalization.CultureInfo.InvariantCulture) + "m";
        }
        return null;
    }

