static IReadOnlyList<string> ServiceParams(string serviceCode, string spName)
{
    int spAt = serviceCode.IndexOf("\"" + spName + "\"", StringComparison.Ordinal);
    if (spAt < 0)
    {
        return [];
    }
    int start = serviceCode.LastIndexOf("GetAll(", spAt, StringComparison.Ordinal);
    string region = serviceCode[(start < 0 ? 0 : start)..spAt];
    return Regex.Matches(region, "Add\\(\"@([A-Za-z0-9_]+)\"").Select(m => m.Groups[1].Value).Distinct().ToList();
}

static string? FindRepoRoot(string dir)
{
    for (var d = new DirectoryInfo(dir); d != null; d = d.Parent)
    {
        if (File.Exists(Path.Combine(d.FullName, "CLAUDE.md")) && Directory.Exists(Path.Combine(d.FullName, "docs", "reference")))
        {
            return d.FullName;
        }
    }
    return null;
}

internal sealed class Options
{
    public string? Root { get; private set; }
    public HashSet<string> Only { get; } = new(StringComparer.OrdinalIgnoreCase);
    public HashSet<string> Layers { get; } = new(StringComparer.OrdinalIgnoreCase);
    public bool Force { get; private set; }
    public bool DryRun { get; private set; }
    public bool Verbose { get; private set; }

    public static Options Parse(string[] args)
    {
        var o = new Options();
        for (int i = 0; i < args.Length; i++)
        {
            switch (args[i])
            {
                case "--root": o.Root = args[++i]; break;
                case "--only": foreach (var s in args[++i].Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)) o.Only.Add(s); break;
                case "--layers": foreach (var s in args[++i].Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)) o.Layers.Add(s); break;
                case "--force": o.Force = true; break;
                case "--skip-existing": o.Force = false; break; // mặc định: không ghi đè file đã có (trừ entity + file tổng hợp)
                case "--dry-run": o.DryRun = true; break;
                case "-v": case "--verbose": o.Verbose = true; break;
                default: throw new ArgumentException($"Tham số lạ: {args[i]}. Xem tools/AppDelicare.CodeGen/README.md");
            }
        }
        return o;
    }
}
