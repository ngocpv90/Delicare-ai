var selected = options.Only.Count == 0 ? all : all.Where(t => options.Only.Contains(t.Name) || options.Only.Contains(Metadata.ClassOf(t.Name))).ToList();
if (options.Only.Count > 0 && selected.Count != options.Only.Count)
{
    var missing = options.Only.Where(o => !all.Any(t => t.Name.Equals(o, StringComparison.OrdinalIgnoreCase) || Metadata.ClassOf(t.Name).Equals(o, StringComparison.OrdinalIgnoreCase)));
