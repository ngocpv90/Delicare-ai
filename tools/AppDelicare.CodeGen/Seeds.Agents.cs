    /// <summary>AI-16: màn Xem thêm ngoài vai trò soi (PKG soi Bếp – OPS-KIT – nhưng cần Sổ hộp khay để biết khách đang giữ bao nhiêu hộp).</summary>
    public static readonly Dictionary<string, string[]> AgentExtraScreens = new() { ["PKG"] = ["log-packaging-ledger"] };

    /// <summary>Id tài khoản agent cố định (MD5 "delicare-agent-&lt;MÃ&gt;") – test / script tham chiếu được.</summary>
    public static Guid AgentUserId(string code) => new(MD5.HashData(Encoding.UTF8.GetBytes("delicare-agent-" + code.ToUpperInvariant())));

    /// <summary>Màn agent được Xem: màn vai trò soi có Truy cập, trừ mục duyệt / quản trị / "Việc của tôi".</summary>
    public static IEnumerable<string> AgentScreens(string? mirror)
        => mirror == null || !ScreenMatrix.TryGetValue(mirror, out var m) ? []
            : m.Where(kv => kv.Value.A && !kv.Key.StartsWith("wf-inbox", StringComparison.Ordinal) && kv.Key != "hr-my" && !kv.Key.StartsWith("adm-", StringComparison.Ordinal))
                .Select(kv => kv.Key).OrderBy(s => s, StringComparer.Ordinal);

    public static string AgentSeed()
    {
        var sb = new StringBuilder();
        sb.AppendLine("""
            -- <auto-generated> tools/AppDelicare.CodeGen (Seeds.Agents.cs) – AI-2 (D-133): danh tính 13 agent Trợ lý AI. Sửa ở generator rồi chạy lại, không sửa tay.
            -- Idempotent, CHỈ THÊM (khóa: ChannelCode / Id tài khoản / tên nhóm / BotCode / ExternalUserId / nhóm × menu) – không ghi đè công tắc (BotStatus) đã chỉnh trên màn.
            -- KHÔNG bí mật: SecretReference = TÊN biến môi trường giữ khóa agent (AGENT_KEY_<MÃ>) – khóa thật chỉ ở env / user-secrets của toolgateway.
            -- Tài khoản agent: INTERNAL, PassWord '!NO-LOGIN!' (không băm khớp), không admin; LoginService chặn đăng nhập web theo liên kết UserExternalIdentity kênh HERMES.
            -- Quyền: CHỈ Xem, trên các màn vai trò người tương ứng được truy cập (ma trận Menu5). Đợt 1 bật VIVI, WH, KITCHEN, QA, KNOW; đợt 2 (AI-10) bật thêm SALES, PROC, LOG, HR (DB cũ: script 1 lần AI10_activate_agents.sql); đợt 3 (AI-16) bật PLAN, PKG, ACC (AI16_activate_agents.sql); đợt 4 (AI-19) bật CSKH (AI19_activate_cskh.sql) – đủ 13 agent.
            SET NOCOUNT ON;
            SET XACT_ABORT ON;
            SET QUOTED_IDENTIFIER ON;
            DECLARE @SeedBy UNIQUEIDENTIFIER = (SELECT TOP (1) Id FROM [dbo].[User] WHERE UserName = N'system' AND IsDeleted = 0);
            IF @SeedBy IS NULL SET @SeedBy = (SELECT TOP (1) Id FROM [dbo].[User] WHERE UserName = N'admin' AND IsDeleted = 0);
            IF @SeedBy IS NULL THROW 50001, N'Không có tài khoản system / admin để ghi CreatedBy cho seed.', 1;
            DECLARE @Now DATETIME2 = SYSDATETIME();
            BEGIN TRAN;

            IF NOT EXISTS (SELECT 1 FROM [dbo].[IntegrationChannel] WHERE ChannelCode = N'HERMES' AND IsDeleted = 0)
                INSERT INTO [dbo].[IntegrationChannel] (Id, ChannelCode, ChannelName, ProviderCode, EnvironmentCode, ChannelStatus, ConfigJson, SecretReference, Note, CreatedDate, CreatedBy, IsDeleted)
                VALUES (NEWID(), N'HERMES', N'Hermes – Trợ lý AI (agent)', N'HERMES', N'Development', N'Active', N'{}', NULL, N'AI-2 seed (D-133) – danh mục agent = BotConfiguration của kênh này', @Now, @SeedBy, 0);
            DECLARE @Ch UNIQUEIDENTIFIER = (SELECT TOP (1) Id FROM [dbo].[IntegrationChannel] WHERE ChannelCode = N'HERMES' AND IsDeleted = 0);

            DECLARE @A TABLE (Code NVARCHAR(50), Name NVARCHAR(255), Audience NVARCHAR(100), Status NVARCHAR(30), UserId UNIQUEIDENTIFIER);
            """);
        sb.AppendLine("INSERT INTO @A VALUES");
        sb.AppendLine(string.Join(",\n", Agents.Select(a => $"    ({Sql(a.Code)}, {Sql(a.Name)}, {Sql(a.Audience)}, {Sql(a.Wave1 ? "Active" : "Inactive")}, '{AgentUserId(a.Code)}')")) + ";");
        sb.AppendLine("""

            INSERT INTO [dbo].[User] (Id, UserName, PassWord, IsActive, IsAdmin, IsDefault, AccountType, CreatedDate, CreatedBy, IsDeleted)
            SELECT a.UserId, N'agent.' + LOWER(a.Code), N'!NO-LOGIN!', 1, 0, 0, N'INTERNAL', @Now, @SeedBy, 0
            FROM @A a
            WHERE NOT EXISTS (SELECT 1 FROM [dbo].[User] u WHERE u.Id = a.UserId OR (u.UserName = N'agent.' + LOWER(a.Code) AND u.IsDeleted = 0));

            INSERT INTO [dbo].[UserGroup] (Id, Name, Code, Description, IsDefault, CreatedDate, CreatedBy, IsDeleted)
            SELECT NEWID(), N'AGENT_' + a.Code, N'AGENT_' + a.Code, N'Nhóm quyền của agent ' + a.Name + N' (AI-2, D-133) – chỉ Xem', 0, @Now, @SeedBy, 0
            FROM @A a
            WHERE NOT EXISTS (SELECT 1 FROM [dbo].[UserGroup] g WHERE ISNULL(NULLIF(g.Code, N''), g.Name) = N'AGENT_' + a.Code AND g.IsDeleted = 0);

            INSERT INTO [dbo].[UserClaim] (Id, UserId, UserGroupId, CreatedDate, CreatedBy, IsDeleted)
            SELECT NEWID(), a.UserId, g.Id, @Now, @SeedBy, 0
            FROM @A a JOIN [dbo].[UserGroup] g ON ISNULL(NULLIF(g.Code, N''), g.Name) = N'AGENT_' + a.Code AND g.IsDeleted = 0
            WHERE NOT EXISTS (SELECT 1 FROM [dbo].[UserClaim] c WHERE c.UserId = a.UserId AND c.UserGroupId = g.Id AND c.IsDeleted = 0);

            INSERT INTO [dbo].[BotConfiguration] (Id, IntegrationChannelId, BotCode, BotName, TargetAudience, WebhookPath, BotStatus, SecretReference, Note, CreatedDate, CreatedBy, IsDeleted)
            SELECT NEWID(), @Ch, a.Code, a.Name, a.Audience, NULL, a.Status, N'AGENT_KEY_' + a.Code, N'AI-2 seed (D-133) – tài khoản agent.' + LOWER(a.Code), @Now, @SeedBy, 0
            FROM @A a
            WHERE NOT EXISTS (SELECT 1 FROM [dbo].[BotConfiguration] b WHERE b.IntegrationChannelId = @Ch AND b.BotCode = a.Code AND b.IsDeleted = 0);

            INSERT INTO [dbo].[UserExternalIdentity] (Id, UserId, IntegrationChannelId, ExternalUserId, ExternalUsername, DisplayName, LinkedAt, IdentityStatus, CreatedDate, CreatedBy, IsDeleted)
            SELECT NEWID(), a.UserId, @Ch, a.Code, N'agent.' + LOWER(a.Code), a.Name, @Now, N'Active', @Now, @SeedBy, 0
            FROM @A a
            WHERE NOT EXISTS (SELECT 1 FROM [dbo].[UserExternalIdentity] x WHERE x.IntegrationChannelId = @Ch AND x.ExternalUserId = a.Code AND x.IsDeleted = 0);

            DECLARE @R TABLE (GroupName NVARCHAR(100), MetaLink NVARCHAR(400));
            """);
        var rows = Agents.SelectMany(a => AgentScreens(a.Mirror).Concat(AgentExtraScreens.GetValueOrDefault(a.Code) ?? []).Distinct().Select(s => $"    (N'AGENT_{a.Code}', {Sql("#/" + s)})")).ToList();
        if (rows.Count > 0)
        {
            foreach (var chunk in rows.Chunk(400))
            {
                sb.AppendLine("INSERT INTO @R VALUES");
                sb.AppendLine(string.Join(",\n", chunk) + ";");
            }
        }
        sb.AppendLine("""

            INSERT INTO [dbo].[UserRole] (Id, UserGroupId, ObjectMenuId, AllowAccess, AllowAdd, AllowEdit, AllowDelete, AllowPrint, AllowExport, AllowImport, CreatedDate, CreatedBy, IsDeleted)
            SELECT NEWID(), g.Id, m.Id, 1, 0, 0, 0, 0, 0, 0, @Now, @SeedBy, 0
            FROM @R r
            JOIN [dbo].[UserGroup] g ON ISNULL(NULLIF(g.Code, N''), g.Name) = r.GroupName AND g.IsDeleted = 0
            JOIN [dbo].[ObjectMenu] m ON m.MetaLink = r.MetaLink AND m.IsDeleted = 0
            WHERE NOT EXISTS (SELECT 1 FROM [dbo].[UserRole] ur WHERE ur.UserGroupId = g.Id AND ur.ObjectMenuId = m.Id AND ur.IsDeleted = 0);

            COMMIT;
            SELECT (SELECT COUNT(*) FROM [dbo].[BotConfiguration] WHERE IntegrationChannelId = @Ch AND IsDeleted = 0) AS [Agent],
                   (SELECT COUNT(*) FROM [dbo].[BotConfiguration] WHERE IntegrationChannelId = @Ch AND BotStatus = N'Active' AND IsDeleted = 0) AS [Đang bật];
            """);
        return sb.ToString();
    }
